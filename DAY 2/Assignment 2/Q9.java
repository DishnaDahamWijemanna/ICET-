class Q9{
		public static void main(String args[]){
			// 1. Integer Literals
			int decimalInt = 100;
			int hexInt = 0x64;           // 100 in hexadecimal
			long longInt = 10000000000L; // 'L' marks it as a Long
			
			// 2. Floating-Point Literals
			double piDouble = 3.14159;   // Default is double
			float piFloat = 3.14F;       // 'F' marks it as a float
			
			// 3. Character Literal
			char letterA = 'A';
			char newline = '\n';         // Escape sequence literal
			
			// 4. String Literal
			String greeting = "Hello, Java!";
			
			// 5. Boolean Literal
			boolean isJavaFun = true;
		}
}
