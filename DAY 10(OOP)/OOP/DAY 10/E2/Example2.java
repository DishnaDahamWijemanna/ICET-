class Box{
	int length;
	int width;
	int height;
}

class Example2{
		public static void main(String args[]){
				Box b1 =new Box();
				b1.length=12;
				b1.width=5;
				b1.height=3;
				
				System.out.println("length - "+b1.length);
				System.out.println("width - "+b1.width);
				System.out.println("height - "+b1.height);
		}
}
